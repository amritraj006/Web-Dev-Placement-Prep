//Primitive data types: String, Number, Boolean, Null, Undefined, Symbol
//Non-primitive data types: Object, Array, Function, Set, Map, WeakMap, WeakSet

let name = "Amrit";
let age = 25;
let isStudent = true;
let address = null;
let email;
let id = Symbol('id');

console.log(name); // Output: Amrit
console.log(age); // Output: 25
console.log(isStudent); // Output: true
console.log(address); // Output: null
console.log(email); // Output: undefined
console.log(id); // Output: Symbol(id)

console.log(typeof name); // Output: string
console.log(typeof age); // Output: number
console.log(typeof isStudent); // Output: boolean
console.log(typeof address); // Output: object
console.log(typeof email); // Output: undefined
console.log(typeof id); // Output: symbol   





